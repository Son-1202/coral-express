// Writes docs/qa/balance_report.md + .json from a Summary.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { loadGameData } from '../../src/data/schema';
import { diagnosis } from './diagnosis';
import type { Summary } from './metrics';

export interface RunInfo {
  games: number;
  bots: string[];
  minutes: number;
  offlineAt: number;
  offlineHours: number;
  seedBase: number;
  workers: number;
  seconds: number;
}

export function writeReport(base: string, s: Summary, info: RunInfo): void {
  mkdirSync(dirname(base), { recursive: true });
  const passN = s.rows.filter((r) => r.pass === true).length;
  const failN = s.rows.filter((r) => r.pass === false).length;
  const md: string[] = [
    '# Balance report (E1)',
    '',
    `Generated by \`npx tsx scripts/balance.ts --games ${info.games}${info.bots.length < 4 ? ` --bot ${info.bots.join(',')}` : ''} --minutes ${info.minutes} --offline-at ${info.offlineAt}\` ` +
      `(${Object.entries(s.games).map(([k, v]) => `${k} ×${v}`).join(', ')}; seeds ${info.seedBase}…; ${info.workers} workers; ${info.seconds.toFixed(0)} s).`,
    `Active-play limit ${info.minutes} sim-min per game, or until the Grand Terminus. Times are active sim time (offline excluded). ` +
      `Not-reached counts as +∞ in medians/percentiles. **${passN} PASS · ${failN} FAIL**.`,
    '',
    '| Metric | Target | Value | Result | Rule |',
    '|---|---|---|---|---|',
    ...s.rows.map((r) => `| ${r.metric} | ${r.target} | ${r.value} | ${r.pass === null ? '—' : r.pass ? 'PASS' : '**FAIL**'} | ${r.rule} |`),
    '',
    '## Diagnosis',
    '',
    ...diagnosis(s, loadGameData()),
    '',
    '## Definitions',
    '',
    '- **Meaningful goal**: new species this run, carriage, extra slot, track, bond formed, milestone, request completed, Today\'s Special, terminal, line opened, Depot Reset becoming available, reset, upgrade. Gap = longest stretch between goals inside minutes 5–15 of each run (window edges count).',
    '- **Dead time**: longest stretch (after minute 1) with no spending action (fish, level, carriage, slot, decor, habitat, track, special, upgrade); a stall at the end of a game that never reaches the Terminus counts.',
    '- **Income at min 15**: average run Shells/s over the 60 s before minute 15 of run 1 (or before the first reset if it comes earlier).',
    '- **Dominance**: share of the run\'s fish income (`state.speciesShells`) earned by the top species, sampled right before each reset.',
    '- Fare / request shares are of all Shells earned in the game (fish + fares + sights + requests + offline).',
    '',
    '## Species bought before the Terminus (greedy, % of games)',
    '',
    '| Species | % |',
    '|---|---|',
    ...Object.entries(s.species).map(([k, v]) => `| ${k} | ${(v * 100).toFixed(1)}% |`),
    '',
    `Illegal actions attempted: ${Object.entries(s.illegal).map(([k, v]) => `${k} ${v}`).join(', ')}.`,
    '',
  ];
  writeFileSync(`${base}.md`, md.join('\n'));
  writeFileSync(`${base}.json`, JSON.stringify({ info, ...s }, (_k, v: unknown) => (v === Infinity ? 'Infinity' : v), 2));
}
